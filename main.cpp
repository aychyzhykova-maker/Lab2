#include <iostream>
#include <cmath>
using namespace std;

int main() {
    setlocale(LC_ALL, "Ukrainian");

    // Integer12. Задано тризначне число.
    // Вивести число, отримане при прочитанні
    // його цифр справа наліво.

    int n;
    cout << "Integer12. Введіть тризначне число: ";
    cin >> n;

    int a = n / 100;      // Перша цифра
    int b = n / 10 % 10;  // Друга цифра
    int c = n % 10;       // Третя цифра

    // Виведення числа у зворотному порядку
    cout << "Число у зворотному порядку: "
         << c * 100 + b * 10 + a << endl;


    // Boolean37. Перевірити, чи може король
    // за один хід перейти з однієї клітинки
    // шахівниці на іншу.

    int x1, y1, x2, y2;

    cout << "\nBoolean37. Введіть координати короля (x1 y1): ";
    cin >> x1 >> y1;

    cout << "Введіть координати другої клітинки (x2 y2): ";
    cin >> x2 >> y2;

    // Король може переміщатися на одну клітинку
    // у будь-якому напрямку
    cout << "Результат: "
         << (abs(x1 - x2) <= 1 &&
             abs(y1 - y2) <= 1 &&
             (x1 != x2 || y1 != y2)) << endl;


    // Math22. Обчислення значення функції
    // за заданою математичною формулою.

    double x;
    cout << "\nMath22. Введіть x: ";
    cin >> x;

    // Обчислення чисельника дробу
    double numerator = 0.25 * log(abs(x)) *
        sqrt(abs(pow(x, 2) *
        pow(sin(x), 3) * sqrt(cos(x))));

    // Обчислення знаменника дробу
    double denominator = cos(x) +
        0.2 * sqrt(2 * x + sqrt(5 * x));

    // Обчислення результату
    double y = numerator / denominator;

    // Виведення результату на екран
    cout << "Результат y = " << y << endl;

    return 0;
}
